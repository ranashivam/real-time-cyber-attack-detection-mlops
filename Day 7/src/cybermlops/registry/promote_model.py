
from pathlib import Path
import json

import mlflow
from mlflow.tracking import MlflowClient


# Configure the registry paths and existing MLflow tracking server.
PROJECT_ROOT = Path.cwd()
REGISTRY_DIR = PROJECT_ROOT / "artifacts" / "registry"

REGISTRY_PATH = REGISTRY_DIR / "registry.json"
VALIDATION_PATH = REGISTRY_DIR / "validation_results.json"
APPROVED_MODEL_PATH = REGISTRY_DIR / "approved_model.json"

TRACKING_URI = "http://localhost:5000"

# Map registered model names to their local catalogue names.
REGISTERED_MODELS = {
    "CyberAttack_Isolation_Forest": "CyberAttack_Isolation_Forest",
    "CyberAttack_Autoencoder": "CyberAttack_Autoencoder",
}


# Load the validation decisions generated by validate_models.py.
def load_validation_results():
    if not VALIDATION_PATH.exists():
        raise FileNotFoundError(
            f"Validation results not found: {VALIDATION_PATH}"
        )

    with VALIDATION_PATH.open("r", encoding="utf-8") as file:
        return json.load(file)


# Load the local catalogue containing registered model versions.
def load_registry():
    if not REGISTRY_PATH.exists():
        raise FileNotFoundError(
            f"Model catalogue not found: {REGISTRY_PATH}"
        )

    with REGISTRY_PATH.open("r", encoding="utf-8") as file:
        return json.load(file)


# Save the selected approved model and its exact version.
def save_approval_record(approval_record):
    REGISTRY_DIR.mkdir(parents=True, exist_ok=True)

    with APPROVED_MODEL_PATH.open("w", encoding="utf-8") as file:
        json.dump(approval_record, file, indent=4)


# Find the latest registered MLflow version for a model.
def get_latest_version(client, registered_name):
    versions = client.search_model_versions(
        filter_string=f"name='{registered_name}'"
    )

    if not versions:
        raise ValueError(
            f"No registered versions found for {registered_name}."
        )

    return max(
        versions,
        key=lambda version: int(version.version),
    )


# Add the approval decision and its source to an MLflow model version.
def set_approval_tags(client, registered_name, version, status):
    client.set_model_version_tag(
        name=registered_name,
        version=version.version,
        key="validation_status",
        value=status,
    )

    client.set_model_version_tag(
        name=registered_name,
        version=version.version,
        key="approval_source",
        value="Video 7 validation gate",
    )


# Promote the approved model version to the MLflow Staging lifecycle stage.
def promote_to_staging(client, registered_name, version_number):
    client.transition_model_version_stage(
        name=registered_name,
        version=str(version_number),
        stage="Staging",
        archive_existing_versions=False,
    )


# Mark a rejected model version without promoting it.
def keep_rejected_candidate(client, registered_name, version):
    client.set_model_version_tag(
        name=registered_name,
        version=version.version,
        key="promotion_status",
        value="NOT_PROMOTED",
    )


# Validate candidate decisions and promote the single approved model version.
def main():
    mlflow.set_tracking_uri(TRACKING_URI)
    mlflow.set_registry_uri(TRACKING_URI)

    client = MlflowClient(
        tracking_uri=TRACKING_URI,
        registry_uri=TRACKING_URI,
    )

    validation_results = load_validation_results()
    registry = load_registry()

    approved_candidates = []

    for registered_name in REGISTERED_MODELS:
        result = validation_results.get(registered_name)

        if result is None:
            raise KeyError(
                f"Validation result missing for {registered_name}."
            )

        version = get_latest_version(client, registered_name)
        status = result["validation_status"]

        set_approval_tags(
            client,
            registered_name,
            version,
            status,
        )

        print(f"\nModel: {registered_name}")
        print(f"Version: {version.version}")
        print(f"Validation: {status}")

        if status == "APPROVED":
            approved_candidates.append({
                "registered_name": registered_name,
                "version": str(version.version),
                "run_id": version.run_id,
                "validation": result,
            })

        elif status == "REJECTED":
            keep_rejected_candidate(
                client,
                registered_name,
                version,
            )

        else:
            raise ValueError(
                f"Unexpected validation status: {status}"
            )

    if not approved_candidates:
        raise RuntimeError(
            "No model passed validation. Nothing will be promoted."
        )

    if len(approved_candidates) > 1:
        raise RuntimeError(
            "Multiple models are approved. Select one explicitly."
        )

    selected = approved_candidates[0]

    # Pass the version number directly rather than treating it as an object.
    promote_to_staging(
        client,
        selected["registered_name"],
        selected["version"],
    )

    approval_record = {
        "registered_name": selected["registered_name"],
        "version": selected["version"],
        "run_id": selected["run_id"],
        "validation": selected["validation"],
        "approval_status": "APPROVED",
        "stage": "Staging",
    }

    save_approval_record(approval_record)

    # Update the matching version in the local catalogue.
    catalogue_versions = registry.get(
        selected["registered_name"],
        [],
    )

    for catalogue_version in catalogue_versions:
        if str(catalogue_version["version"]) == selected["version"]:
            catalogue_version["status"] = "Staging"
            catalogue_version["promotion_status"] = "PROMOTED"

    with REGISTRY_PATH.open("w", encoding="utf-8") as file:
        json.dump(registry, file, indent=4)

    print("\nModel promotion completed successfully.")
    print(f"Approved model: {selected['registered_name']}")
    print(f"Version: {selected['version']}")
    print("MLflow stage: Staging")
    print(f"Approval record: {APPROVED_MODEL_PATH}")


if __name__ == "__main__":
    main()
